function translateProductName(text: string): string {
  return text.replace(/[A-Za-z0-9]+(?:['-][A-Za-z0-9]+)*/g, (word) => {
    const translated = productNameWords[word]
    return translated ?? word
  })
}

export function translateCatalogName(locale: Locale, text: string): string {
  if (locale === "en") return text
  return productTranslations[text] ?? translateProductName(text)
}

export function translate(locale: Locale, text: string): string {
  if (locale === "en") return text

  const priceRange = text.match(/^\$(\d+) to \$(\d+)$/)
  if (priceRange) {
    return `${formatCurrency(priceRange[1], locale, "BDT")} থেকে ${formatCurrency(priceRange[2], locale, "BDT")}`
  }

  if (text === "Free shipping on orders above $100") {
    return `${formatCurrency(100, locale, "BDT")}-এর বেশি অর্ডারে বিনামূল্যে শিপিং`
  }

  const count = text.match(/^Subtotal \((\d+)\):$/)
  if (count) return `উপমোট (${count[1]}):`
  const stars = text.match(/^(\d+(?:\.\d+)?) stars & up$/)
  if (stars) return `${stars[1]} স্টার বা তার বেশি`

  return (
    interfaceTranslations[text] ??
    categoryTranslations[text] ??
    productTranslations[text] ??
    text
  )
}

export function translateMessage(locale: Locale, message: string): string {
  if (locale === "en") return message

  const exactTranslation = interfaceTranslations[message]
  if (exactTranslation) return exactTranslation

  const addedToCart = message.match(/^(.+?) added to cart$/)
  if (addedToCart) {
    return `${translateCatalogName(locale, addedToCart[1])} কার্টে যোগ করা হয়েছে`
  }

  const updatedInCart = message.match(/^(.+?) updated in cart$/)
  if (updatedInCart) {
    return `${translateCatalogName(locale, updatedInCart[1])} কার্টে আপডেট করা হয়েছে`
  }

  const removedFromCart = message.match(/^(.+?) was removed from cart$/)
  if (removedFromCart) {
    return `${translateCatalogName(locale, removedFromCart[1])} কার্ট থেকে সরানো হয়েছে`
  }

  return message
}
